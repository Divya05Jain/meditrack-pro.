function createSubtasks(overrides = {}) {
  const defaults = {
    triage: { status: 'pending', staffId: null },
    consultation: { status: 'pending', staffId: null },
    diagnostics: { status: 'pending', staffId: null },
    pharmacy: { status: 'pending', staffId: null },
  };

  const merged = { ...defaults, ...overrides };

  return SUBTASK_TYPES.map(({ type, title }) => ({
    id: `ST-${type}`,
    type,
    title,
    status: merged[type].status,
    staffId: merged[type].staffId,
  }));
}

